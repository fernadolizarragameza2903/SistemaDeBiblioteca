-- =====================================================================
-- Sistema de Biblioteca - Esquema de base de datos (PostgreSQL 14+)
-- Ejecutar sobre la base de datos: sistema_biblioteca
--   psql -U postgres -d sistema_biblioteca -f database/01_schema.sql
-- El script es re-ejecutable: elimina y vuelve a crear las tablas.
-- =====================================================================

DROP TABLE IF EXISTS prestamos CASCADE;
DROP TABLE IF EXISTS libros CASCADE;
DROP TABLE IF EXISTS categorias CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- ---------------------------------------------------------------------
-- Funcion comun para mantener actualizada la columna fecha_actualizacion
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_actualizar_fecha_modificacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- ROLES: perfiles de acceso (ADMIN, BIBLIOTECARIO, LECTOR)
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL,
    CONSTRAINT uk_roles_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- USUARIOS: personal de la biblioteca y lectores
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR(100) NOT NULL,
    apellido             VARCHAR(100) NOT NULL,
    email                VARCHAR(150) NOT NULL,
    password_hash        VARCHAR(255) NOT NULL,
    rol_id               BIGINT       NOT NULL,
    activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (rol_id) REFERENCES roles (id)
);

CREATE TRIGGER trg_usuarios_fecha_actualizacion
    BEFORE UPDATE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION fn_actualizar_fecha_modificacion();

-- ---------------------------------------------------------------------
-- CATEGORIAS: clasificacion de los libros
-- ---------------------------------------------------------------------
CREATE TABLE categorias (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL,
    descripcion  VARCHAR(500),
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- LIBROS: catalogo y stock disponible
-- ---------------------------------------------------------------------
CREATE TABLE libros (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo               VARCHAR(255) NOT NULL,
    autor                VARCHAR(255) NOT NULL,
    isbn                 VARCHAR(20)  NOT NULL,
    categoria_id         BIGINT,
    stock                INTEGER      NOT NULL DEFAULT 0,
    activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_libros_isbn UNIQUE (isbn),
    CONSTRAINT ck_libros_stock CHECK (stock >= 0),
    CONSTRAINT fk_libros_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

CREATE INDEX idx_libros_categoria ON libros (categoria_id);
CREATE INDEX idx_libros_titulo ON libros (LOWER(titulo));

-- ---------------------------------------------------------------------
-- PRESTAMOS: registro de libros prestados a usuarios
-- estado: ACTIVO (en manos del lector) | DEVUELTO
-- ---------------------------------------------------------------------
CREATE TABLE prestamos (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id                  BIGINT      NOT NULL,
    libro_id                    BIGINT      NOT NULL,
    fecha_prestamo              TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_devolucion_esperada   DATE        NOT NULL,
    fecha_devolucion_real       TIMESTAMP,
    estado                      VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    observaciones               VARCHAR(500),
    CONSTRAINT fk_prestamos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_prestamos_libro FOREIGN KEY (libro_id) REFERENCES libros (id),
    CONSTRAINT ck_prestamos_estado CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    CONSTRAINT ck_prestamos_fechas CHECK (fecha_devolucion_esperada >= CAST(fecha_prestamo AS DATE))
);

CREATE INDEX idx_prestamos_usuario_estado ON prestamos (usuario_id, estado);
CREATE INDEX idx_prestamos_libro ON prestamos (libro_id);
